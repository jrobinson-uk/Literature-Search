#!/usr/bin/env node
// Writes Version.js (git-ignored) so the spreadsheet can show which code is deployed.
// Usage: node scripts/stamp-version.js <target>   e.g. work | personal
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const git = (args) => {
  try { return execSync(`git ${args}`, { cwd: root, encoding: 'utf8' }).trim(); }
  catch (e) { return ''; }
};

// Guard: refuse to push code that is missing commits from origin/main.
// clasp push replaces the whole live script, so stale code wipes features.
// Override with ALLOW_STALE_PUSH=1 if you really mean it.
if (!process.env.ALLOW_STALE_PUSH) {
  git('fetch --quiet origin');
  const upstream = git('rev-parse --verify --quiet origin/main');
  if (upstream) {
    try {
      execSync(`git merge-base --is-ancestor ${upstream} HEAD`, { cwd: root, stdio: 'ignore' });
    } catch (e) {
      console.error('Refusing to push: this branch is missing commits from origin/main.\n' +
        'Pushing would replace the live script with older code. Merge or rebase onto origin/main first\n' +
        '(or set ALLOW_STALE_PUSH=1 to override).');
      process.exit(1);
    }
  }
}

const info = {
  commit: git('rev-parse --short HEAD') || 'unknown',
  branch: git('rev-parse --abbrev-ref HEAD') || 'unknown',
  commitDate: git('log -1 --format=%cI'),
  dirty: git('status --porcelain') !== '',
  pushedAt: new Date().toISOString(),
  target: process.argv[2] || 'unknown',
};

const out = `// Generated by scripts/stamp-version.js at push time. Do not edit or commit.
const BUILD_INFO = ${JSON.stringify(info, null, 2)};
`;
fs.writeFileSync(path.join(root, 'Version.js'), out);
console.log(`Stamped ${info.commit}${info.dirty ? ' (uncommitted changes)' : ''} for ${info.target}`);
